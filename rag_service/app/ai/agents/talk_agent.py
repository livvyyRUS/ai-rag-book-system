class TalkAgent:
    def __init__(self, user_id: str):
        self.user_id = user_id
        # Инициализируем историю для этого пользователя
        if self.user_id not in _session_history:
            _session_history[self.user_id] = []

    async def message(
        self,
        query: str,
        found: bool = False,
        fragments: Optional[list] = None
    ) -> str:
        """
        Обработка вопроса с результатами от RAG-агента.

        :param query: текущий вопрос пользователя
        :param found: найдены ли фрагменты (true/false)
        :param fragments: список фрагментов (может быть пустым)
        """
        fragments = fragments or []

        # Форматируем фрагменты для промпта
        if fragments:
            fragments_text = "\n\n".join([
                f"=== ФРАГМЕНТ {i+1} ===\n"
                f"Книга: {f.get('book', 'Неизвестно')}\n"
                f"Местоположение: {f.get('location', 'Неизвестно')}\n"
                f"Текст:\n{f.get('text', '')}\n"
                f"==================="
                for i, f in enumerate(fragments)
            ])
        else:
            fragments_text = "Фрагменты не найдены"

        # Получаем историю
        history = _session_history.get(self.user_id, [])

        try:
            # Создаем промпт вручную
            messages = _create_prompt(query, str(found), fragments_text, history)
            
            # Вызываем LLM
            response: AIMessage = await llm.ainvoke(messages)
            print(f"💬 TalkAgent: {response.content[:100]}...")

            # Сохраняем в историю
            _session_history[self.user_id].append(HumanMessage(content=query))
            _session_history[self.user_id].append(response)

            return response.content
        except Exception as e:
            print(f"Ошибка TalkAgent: {e}")
            return f"Извините, произошла ошибка: {str(e)}"
